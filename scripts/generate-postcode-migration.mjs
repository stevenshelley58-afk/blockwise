#!/usr/bin/env node
// Generates the refresh_policies seed VALUES rows from hermes/data/au-postcodes.json.
// Usage: node scripts/generate-postcode-migration.mjs > supabase/migrations/202606020001_seed_national_postcodes.sql
//
// Priority drives census ordering (lower = sooner). Perth metro is built first,
// then the rest of WA, then the eastern states, matching the "Perth blitz" goal.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const postcodes = JSON.parse(readFileSync(join(__dirname, "../hermes/data/au-postcodes.json"), "utf8"));

// The original hardcoded Perth-metro roster — these get top priority.
const PERTH_METRO = new Set([
  "6000", "6005", "6006", "6007", "6008", "6009", "6010", "6011", "6014", "6015",
  "6016", "6017", "6018", "6019", "6020", "6050", "6051", "6052", "6151", "6152",
  "6153", "6158", "6159", "6160", "6166",
]);

const STATE_PRIORITY = { WA: 2, NSW: 3, VIC: 3, QLD: 4, SA: 4, TAS: 5, ACT: 5, NT: 6 };
const CADENCE = { WA: 720, NSW: 1440, VIC: 1440, QLD: 2880, SA: 2880, TAS: 4320, ACT: 4320, NT: 4320 };

const seen = new Set();
const rows = [];
for (const { postcode, state } of postcodes) {
  const key = `${postcode}:${state}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const priority = state === "WA" && PERTH_METRO.has(postcode) ? 1 : (STATE_PRIORITY[state] ?? 6);
  const cadence = CADENCE[state] ?? 4320;
  rows.push(`  ('${postcode}', '${state}', true, ${priority}, ${cadence}, now())`);
}

process.stdout.write(
  `-- Seed research.refresh_policies for every Australian postcode in hermes/data/au-postcodes.json.\n` +
    `-- Generated by scripts/generate-postcode-migration.mjs (do not hand-edit).\n` +
    `-- Priority: Perth metro = 1, rest of WA = 2, NSW/VIC = 3, QLD/SA = 4, TAS/ACT = 5, NT = 6.\n` +
    `-- Cadence (minutes): WA 720, NSW/VIC 1440, QLD/SA 2880, TAS/ACT/NT 4320.\n` +
    `-- next_refresh_at = now() so every row is immediately eligible; priority governs ordering.\n` +
    `INSERT INTO research.refresh_policies (postcode, state, active, priority, refresh_cadence_minutes, next_refresh_at)\n` +
    `VALUES\n${rows.join(",\n")}\n` +
    `ON CONFLICT (postcode, state) DO UPDATE SET\n` +
    `  active = true,\n` +
    `  priority = LEAST(research.refresh_policies.priority, EXCLUDED.priority);\n`,
);
