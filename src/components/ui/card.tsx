import * as React from "react"

import { cn } from "@/lib/utils"

function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      className={cn(
        // Card role radius (16px), not the generic `rounded-lg` (12px). Padding
        // is 16px on a phone and 24px from `md`, per the spacing scale.
        "flex flex-col gap-6 rounded-(--r-card) border bg-card py-4 text-card-foreground md:py-6",
        className
      )}
      {...props}
    />
  )
}

